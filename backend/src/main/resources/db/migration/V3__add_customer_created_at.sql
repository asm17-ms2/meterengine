-- ============================================================================
-- V3: customer에 등록 시각(created_at) 추가 (MS2-171, 스토리 MS2-146)
--
-- 목표 형태는 "고객 행이 생긴 시각을 DB가 스스로 남긴다"다. 앱이 값을 계산해
-- 넣는 것이 아니라 컬럼 기본값이 채운다.
--
-- 이번 슬라이스는 컬럼을 세우는 데서 끝난다. 엔티티 매핑과 응답 노출은 같은
-- 스토리의 다음 단계다. ddl-auto=validate는 엔티티에 매핑된 것만 검사하므로
-- 아직 매핑하지 않은 이 컬럼은 기동을 막지 않는다.
--
-- 범위 밖 (이관, 누락 아님):
--   - 클라이언트가 보낸 created_at을 무시하는 강제(BEFORE INSERT 트리거).
--     V1의 usage_event.received_at에는 그 트리거가 있다. 여기 두지 않는 이유는
--     "필요 없어서"가 아니라 "고객 등록 시각에 대한 팀 정책을 아직 못 찾아서"다.
--     received_at의 트리거는 스토리 MS2-121의 "클라이언트 값은 무시한다"를
--     집행한 것인데 created_at에 대응하는 결정을 레포에서 찾지 못했다(Notion과
--     Miro는 확인하지 않았다). 정책이 확인되면 후속 마이그레이션으로 올린다.
--     그때까지 아래 DEFAULT는 컬럼을 생략한 INSERT만 채우고, 값을 명시한
--     INSERT와 ORM 밖의 UPDATE는 막지 않는다
--   - updated_at, 등록자, 변경 이력: 미정
--   - 다른 테이블의 created_at: 이 스토리 범위 밖
--
-- 검사 공백 (알고 넘어간다):
--   기존 행이 무슨 값을 받는지는 CI에서 확인되지 않는다. Testcontainers는 매번
--   빈 DB이고, R__seed.sql은 반복 마이그레이션이라 versioned가 다 돈 뒤에 실행
--   되므로 이 파일이 도는 시점에 customer가 0행이기 때문이다. 행이 있는 DB에서
--   한 번 확인해야 하고, 그 대상은 개발자 로컬 DB뿐이다.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. 컬럼 추가와 기존 행 채우기
-- now()가 stable이라 PostgreSQL 11+의 고속 경로를 탄다. 테이블을 재작성하지
-- 않고 기본값 하나를 메타데이터로 저장해 기존 행 전부가 그 값을 공유한다
-- (pg_attribute.atthasmissing). 그래서 NOT NULL이 같은 문장에서 공짜로 붙고,
-- 전 행 UPDATE도 필요 없다.
--
-- 기존 행이 받는 이 값은 실제 등록 시각이 아니다. 등록 시각을 기록하기 전에
-- 만들어진 행이라 그 사실이 어디에도 남아 있지 않다. 마이그레이션 시각을
-- "모른다"의 자리표시자로 넣는다. 값이 전부 같다는 것 자체가 "이 행들은
-- 백필이다"를 알린다.
--
-- 여기서 clock_timestamp()를 쓰면 안 된다. volatile이라 고속 경로를 못 타고
-- 테이블을 재작성하면서 기본식을 행마다 평가한다. 기록된 적 없는 등록 순서가
-- 행마다 다른 값으로 박힌다.
-- ----------------------------------------------------------------------------
ALTER TABLE customer ADD COLUMN created_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- ----------------------------------------------------------------------------
-- 2. 이후 INSERT의 기본값을 문장 시각으로 바꾼다
-- 1절의 now()는 백필 전용이다. 앞으로 들어오는 행에까지 now()가 남으면 한
-- 트랜잭션에서 여러 고객을 넣을 때 전부 트랜잭션 시작 시각으로 같아진다.
-- clock_timestamp()는 문장 실행 시각을 주므로 각자의 시각이 남는다. 이미 저장된
-- 백필 값은 이 문장에 영향받지 않는다(기본값 변경은 기존 행을 건드리지 않는다).
--
-- V1의 usage_event.received_at도 clock_timestamp()를 쓴다. 두 컬럼의 함수 선택을
-- 정한 팀 결정은 레포에서 찾지 못했고, 일관성으로 맞춘 것이다.
-- ----------------------------------------------------------------------------
ALTER TABLE customer ALTER COLUMN created_at SET DEFAULT clock_timestamp();
